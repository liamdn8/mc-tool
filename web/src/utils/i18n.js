const LOCAL_STORAGE_KEY = 'mc-tool-language';
const DEFAULT_LANGUAGE = 'vi';
const FALLBACK_LANGUAGE = 'en';

const interpolate = (template, variables = {}) => {
    if (typeof template !== 'string' || !variables) {
        return template;
    }

    return template.replace(/\{([^}]+)\}/g, (match, key) => {
        const trimmed = key.trim();
        return Object.prototype.hasOwnProperty.call(variables, trimmed)
            ? variables[trimmed]
            : match;
    });
};

const I18nContext = createContext({
    currentLang: DEFAULT_LANGUAGE,
    setLanguage: () => {},
    t: (key, fallback) => fallback ?? key,
});

const resolveInitialLanguage = () => {
    if (typeof window !== 'undefined') {
        const stored = window.localStorage.getItem(LOCAL_STORAGE_KEY);
        if (stored && translations[stored]) {
            return stored;
        }
    }
    return DEFAULT_LANGUAGE;
};

export const I18nProvider = ({ children }) => {
    const [currentLang, setCurrentLang] = useState(resolveInitialLanguage);

    useEffect(() => {
        if (typeof window === 'undefined') {
            return;
        }

        const stored = window.localStorage.getItem(LOCAL_STORAGE_KEY);
        if (stored && translations[stored] && stored !== currentLang) {
            setCurrentLang(stored);
        }
    }, []);

    useEffect(() => {
        if (typeof window !== 'undefined') {
            window.localStorage.setItem(LOCAL_STORAGE_KEY, currentLang);
        }
    }, [currentLang]);

    const setLanguage = useCallback((lang) => {
        if (lang && translations[lang]) {
            setCurrentLang(lang);
        }
    }, []);

    const t = useCallback(
        (key, fallback, variables) => {
            if (!key) {
                return '';
            }

            const template =
                translations[currentLang]?.[key] ??
                translations[DEFAULT_LANGUAGE]?.[key] ??
                translations[FALLBACK_LANGUAGE]?.[key] ??
                fallback ??
                key;

            return interpolate(template, variables);
        },
        [currentLang]
    );

    const value = useMemo(
        () => ({
            currentLang,
            setLanguage,
            t,
        }),
        [currentLang, setLanguage, t]
    );

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
    const context = useContext(I18nContext);
    if (!context) {
        throw new Error('useI18n must be used within an I18nProvider');
    }
    return context;
};